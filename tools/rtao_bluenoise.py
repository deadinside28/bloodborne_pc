# bbport: the ray-traced AO's sampling texture (vk_rtao.cpp): 64x64 blue noise, four independent
# channels, by Ulichney's void-and-cluster method (toroidal Gaussian energy, sigma 1.9). Writes
# a C++ header with the RGBA8 texels. Deterministic (fixed seed): run it again to regenerate.
#   python3 tools/rtao_bluenoise.py gpu/shadps4/video_core/renderer_vulkan/rtao_bluenoise.h
import sys
import numpy as np

N = 64
SIGMA = 1.9


def energy_kernel():
    d = np.minimum(np.arange(N), N - np.arange(N)).astype(np.float64)
    r2 = d[:, None] ** 2 + d[None, :] ** 2
    return np.fft.rfft2(np.exp(-r2 / (2 * SIGMA * SIGMA)))


KERNEL = energy_kernel()


def energy(pattern):
    return np.fft.irfft2(np.fft.rfft2(pattern) * KERNEL, s=(N, N))


def void_and_cluster(rng):
    # Initial pattern: 10% random points, relaxed until the tightest cluster is the largest void.
    pattern = np.zeros((N, N))
    pattern.flat[rng.choice(N * N, N * N // 10, replace=False)] = 1.0
    while True:
        e = energy(pattern)
        cluster = np.argmax(np.where(pattern == 1, e, -np.inf))
        pattern.flat[cluster] = 0.0
        e = energy(pattern)
        void = np.argmin(np.where(pattern == 0, e, np.inf))
        if void == cluster:
            pattern.flat[cluster] = 1.0
            break
        pattern.flat[void] = 1.0
    initial = pattern.copy()
    ones = int(initial.sum())
    rank = np.zeros(N * N, dtype=np.int64)
    # Phase 1: remove the tightest clusters of the initial pattern, ranks ones-1 .. 0.
    p = initial.copy()
    for r in range(ones - 1, -1, -1):
        e = energy(p)
        cluster = np.argmax(np.where(p == 1, e, -np.inf))
        p.flat[cluster] = 0.0
        rank[cluster] = r
    # Phase 2 and 3: fill the largest voids, ranks ones .. N*N-1.
    p = initial.copy()
    for r in range(ones, N * N):
        e = energy(p)
        void = np.argmin(np.where(p == 0, e, np.inf))
        p.flat[void] = 1.0
        rank[void] = r
    return ((rank.reshape(N, N) + 0.5) * 256 / (N * N)).astype(np.uint8)


def main():
    rng = np.random.default_rng(20261015)
    channels = [void_and_cluster(rng) for _ in range(4)]
    texels = np.stack(channels, axis=-1).reshape(-1)
    with open(sys.argv[1], "w") as out:
        out.write("// SPDX-License-Identifier: GPL-2.0-or-later\n")
        out.write("// bbport: generated by tools/rtao_bluenoise.py (64x64 RGBA8 blue noise, four channels).\n")
        out.write("#pragma once\n#include <array>\n#include <cstdint>\n\nnamespace Rtao {\n")
        out.write(f"inline constexpr std::uint32_t BlueNoiseSize = {N};\n")
        out.write(f"inline constexpr std::array<std::uint8_t, {texels.size}> BlueNoise = {{\n")
        for i in range(0, texels.size, 24):
            out.write("    " + ", ".join(str(v) for v in texels[i:i + 24]) + ",\n")
        out.write("};\n} // namespace Rtao\n")


if __name__ == "__main__":
    main()
